/** 조각들을 부위(data-part) 구조로 묶는다 */
export function figure(o: {
  legs: string;
  torso: string;
  /** 머리카락·너울 (흔들리는 부위) */
  hair: string;
  face: string;
  /** 수염 등 얼굴에 붙는 것 */
  beard?: string;
  cloth: string;
  frontArm: string;
  /** 땅에 붙어 있어야 하는 소품 (지팡이 등) */
  ground?: string;
  /** 앞팔보다 위에 겹치는 소품 (어깨에 멘 밧줄 등) */
  over?: string;
  /** 머리 크기·위치 */
  head?: string;
}): string {
  return `
    <g data-part="legs">${o.ground ?? ''}${o.legs}</g>
    <g data-part="upper">
      <g data-part="armL">${BACK_ARM}</g>
      ${o.torso}
      <g data-part="head">
        <g transform="${o.head ?? 'matrix(0.88 0 0 0.88 13 10)'}">
          <g data-part="hair">${o.hair}</g>
          ${o.face}
          ${o.beard ?? ''}
        </g>
      </g>
      <g data-part="cloth" class="tone2">${o.cloth}</g>
      ${o.frontArm}
      ${o.over ?? ''}
    </g>`;
}
