export const BOOKS: Book[] = RAW.map(([code, name, abbr, chapters], i) => ({
  no: i + 1,
  code,
  name,
  abbr,
  chapters,
  testament: i < 39 ? 'OT' : 'NT',
}));

export const TOTAL_CHAPTERS = BOOKS.reduce((s, b) => s + b.chapters, 0);

const byKey = new Map<string, Book>();
for (const b of BOOKS) {
  byKey.set(b.code, b);
  byKey.set(b.name, b);
  byKey.set(b.abbr, b);
}

/** 약칭·이름·코드 어느 것으로도 찾는다. */
export function findBook(key: string): Book | undefined {
  return byKey.get(key.trim()) ?? byKey.get(key.trim().toUpperCase());
}
