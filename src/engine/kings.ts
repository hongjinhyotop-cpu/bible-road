/** beat 필드 "kings" 형식 (fx/kingdoms.ts)
 *  - "ahab" 또는 ["ahab", "jehoshaphat"]   : 두 왕국 판을 크게 펴고, 그 왕 카드를 쌓는다. 이 왕보다 앞선 왕들은 이미 쌓여 있다
 *  - { "add": [...], "fall": "israel" }     : 북쪽(또는 남쪽)이 무너짐 (왕하 17 / 25)
 *  - { "show": true }                        : 지금 상태 그대로 크게 보여 줌
 *  다음 beat에 kings가 없으면 판은 오른쪽 위의 작은 표(북 · 남 지금 왕)로 물러나 에피소드 내내 남는다 */
