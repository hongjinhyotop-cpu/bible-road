/** evil = "여호와 보시기에 악을 행하여" · right = "정직히 행하여" · mixed = 둘 다 들어 있음 · none = 본문에 평가가 없음 */
export type Verdict = 'evil' | 'right' | 'mixed' | 'none';

export interface King {
  id: string;
  name: string;
  kingdom: Kingdom;
  /** 재위 기간 (개역한글 표현을 숫자로: "22년", "7일", "6개월") */
  reign: string;
  /** 즉위할 때 나이 (본문에 있을 때만, 유다 왕들) */
  age?: number;
  verdict: Verdict;
  /** 카드에 적는 평가 문구 — 본문 구절에서 그대로 */
  quote: string;
  /** 평가 구절 */
  ref: string;
  /** 친구 말투 한 줄 */
  note: string;
  /** 즉위 연도 (주전, 대략 — 시간 축 위치) */
  year: number;
}

const k = (id: string, name: string, kingdom: Kingdom, reign: string, verdict: Verdict, quote: string, ref: string, year: number, note: string, age?: number): King =>
  ({ id, name, kingdom, reign, verdict, quote, ref, year, note, ...(age != null ? { age } : {}) });

